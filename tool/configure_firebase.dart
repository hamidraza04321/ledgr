// Reads android/app/google-services.json and writes:
//   lib/firebase_options.dart
//   lib/core/config/google_web_client.dart
//   lib/core/config/app_check_token.dart (only if missing; never replaced)
//
// Usage (from the project folder):
//   dart run tool/configure_firebase.dart
import 'dart:convert';
import 'dart:io';
import 'dart:math';

const packageName = 'com.ledgrapp.ledgr';

void main() {
  final file = File('android/app/google-services.json');
  if (!file.existsSync()) {
    _fail('android/app/google-services.json not found.\n'
        'Download it from Firebase console → Project settings → Your apps → '
        'Android app ($packageName) and put it in android/app/.');
  }

  final json = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
  final project = json['project_info'] as Map<String, dynamic>;
  final clients = (json['client'] as List).cast<Map<String, dynamic>>();
  final client = clients.firstWhere(
    (c) =>
        (c['client_info']?['android_client_info']?['package_name']) ==
        packageName,
    orElse: () => _fail(
        'google-services.json has no Android app with package "$packageName".\n'
        'Add an Android app with exactly that package name in Firebase.'),
  );

  final apiKey = (client['api_key'] as List).first['current_key'] as String;
  final appId = client['client_info']['mobilesdk_app_id'] as String;

  final oauth = <Map<String, dynamic>>[
    ...((client['oauth_client'] as List?) ?? const []).cast<Map<String, dynamic>>(),
    ...((client['services']?['appinvite_service']?['other_platform_oauth_client']
                as List?) ??
            const [])
        .cast<Map<String, dynamic>>(),
  ];
  final webClient = oauth.firstWhere(
    (o) => o['client_type'] == 3,
    orElse: () => const {},
  )['client_id'] as String?;
  final hasAndroidClient = oauth.any((o) => o['client_type'] == 1);

  File('lib/firebase_options.dart').writeAsStringSync('''
// Generated by tool/configure_firebase.dart. Do not edit by hand.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      throw UnsupportedError('Ledgr is not configured for web.');
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      default:
        throw UnsupportedError('Ledgr is only configured for Android.');
    }
  }

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '$apiKey',
    appId: '$appId',
    messagingSenderId: '${project['project_number']}',
    projectId: '${project['project_id']}',
    storageBucket: '${project['storage_bucket'] ?? ''}',
  );
}
''');

  File('lib/core/config/google_web_client.dart').writeAsStringSync('''
// Generated by `dart run tool/configure_firebase.dart`.
// The OAuth "Web client" ID that Google Sign-In uses to issue an ID token
// for Firebase Auth. Leave empty until Firebase is configured.
const String googleWebClientId = '${webClient ?? ''}';
''');

  stdout.writeln('✓ Wrote lib/firebase_options.dart '
      '(project ${project['project_id']})');
  stdout.writeln(webClient == null
      ? '! No Web client ID found. Enable Google sign-in in Firebase '
          'Authentication, download google-services.json again and re-run.'
      : '✓ Wrote lib/core/config/google_web_client.dart');
  if (!hasAndroidClient) {
    stdout.writeln('! No Android OAuth client found. Add your SHA-1 '
        'fingerprint in Firebase → Project settings → Your apps, then '
        'download google-services.json again and re-run.');
  }

  final tokenFile = File('lib/core/config/app_check_token.dart');
  if (!tokenFile.existsSync()) {
    tokenFile.writeAsStringSync('''
// Generated by `dart run tool/configure_firebase.dart`.
// App Check debug token for side-loaded APKs (Play Integrity only works for
// Play Store installs). Register it once in Firebase console:
//   App Check -> Apps -> Ledgr -> ⋮ -> Manage debug tokens -> Add debug token
// Leave empty to use Play Integrity instead (for a Play Store release).
const String appCheckToken = '${_uuidV4()}';
''');
    stdout.writeln('✓ Wrote lib/core/config/app_check_token.dart — register '
        'this token in App Check → Apps → Manage debug tokens.');
  }
}

String _uuidV4() {
  final r = Random.secure();
  final b = List<int>.generate(16, (_) => r.nextInt(256));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  final h = b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();
  return '${h.substring(0, 8)}-${h.substring(8, 12)}-${h.substring(12, 16)}-'
      '${h.substring(16, 20)}-${h.substring(20)}';
}

Never _fail(String message) {
  stderr.writeln('✗ $message');
  exit(1);
}
